<?php

declare(strict_types=1);

namespace Musikhood\AuthClient\Install;

use Symfony\Component\Yaml\Exception\ParseException;
use Symfony\Component\Yaml\Yaml;

/**
 * Plans `config/packages/nelmio_cors.yaml` (only when NelmioCorsBundle is
 * installed): cookies need `allow_credentials: true`, auth-client >= 2.2 sends
 * `X-Device-Fp` on every request (preflight), and the 429 response exposes
 * `Retry-After`.
 *
 * Edits are line-level inside `nelmio_cors.defaults` (flow lists like the
 * Nelmio recipe writes them) and are verified by re-parsing the result;
 * anything else → a snippet to paste.
 */
final class CorsConfigurator
{
    public const PATH = 'config/packages/nelmio_cors.yaml';

    public const DEVICE_HEADER = 'X-Device-Fp';
    public const RETRY_AFTER_HEADER = 'Retry-After';

    public function plan(string $projectDir, bool $nelmioInstalled): PlannedChange
    {
        if (!$nelmioInstalled) {
            return PlannedChange::manual(self::PATH, 'brak NelmioCorsBundle — jeśli front działa na innym originie: composer require nelmio/cors-bundle i uruchom install ponownie', self::template());
        }

        $file = $projectDir . '/' . self::PATH;
        if (!is_file($file)) {
            return PlannedChange::create(self::PATH, 'CORS z ciasteczkami + X-Device-Fp / Retry-After', self::template());
        }

        $old = (string) file_get_contents($file);
        if (self::satisfies($old)) {
            return PlannedChange::unchanged(self::PATH, 'CORS już obsługuje ciasteczka, X-Device-Fp i Retry-After');
        }

        $new = $this->edit($old);
        if (null !== $new && self::satisfies($new)) {
            return PlannedChange::modify(self::PATH, 'allow_credentials / allow_headers / expose_headers dla auth-client', $old, $new);
        }

        return PlannedChange::manual(self::PATH, 'nie umiem bezpiecznie edytować tego pliku — uzupełnij nelmio_cors.defaults', self::template());
    }

    public static function template(): string
    {
        return <<<YAML
            # Generated by `bin/console auth-client:install` (musikhood/auth-client-bundle).
            nelmio_cors:
                defaults:
                    origin_regex: true
                    allow_origin: ['%env(CORS_ALLOW_ORIGIN)%']
                    # Session cookies (BEARER, refresh_token) travel with XHR only with credentials.
                    allow_credentials: true
                    allow_methods: ['GET', 'OPTIONS', 'POST', 'PUT', 'PATCH', 'DELETE']
                    # X-Device-Fp: device fingerprint sent by auth-client >= 2.2 on every request.
                    allow_headers: ['Content-Type', 'Authorization', 'X-Device-Fp']
                    # Retry-After: 429 too_many_attempts (login / 2FA attempt limit).
                    expose_headers: ['Link', 'Retry-After']
                    max_age: 3600
                paths:
                    '^/': null

            YAML;
    }

    public static function satisfies(string $yaml): bool
    {
        try {
            $parsed = Yaml::parse($yaml);
        } catch (ParseException) {
            return false;
        }
        $defaults = \is_array($parsed) && \is_array($parsed['nelmio_cors']['defaults'] ?? null) ? $parsed['nelmio_cors']['defaults'] : null;
        if (null === $defaults) {
            return false;
        }

        return true === ($defaults['allow_credentials'] ?? false)
            && self::listContains($defaults['allow_headers'] ?? [], self::DEVICE_HEADER)
            && self::listContains($defaults['expose_headers'] ?? [], self::RETRY_AFTER_HEADER);
    }

    private static function listContains(mixed $list, string $header): bool
    {
        if (!\is_array($list)) {
            return '*' === $list;
        }
        foreach ($list as $item) {
            if (\is_string($item) && ('*' === $item || 0 === strcasecmp($item, $header))) {
                return true;
            }
        }

        return false;
    }

    private function edit(string $yaml): ?string
    {
        $lines = explode("\n", $yaml);

        $defaultsIndex = null;
        foreach ($lines as $i => $line) {
            if (1 === preg_match('/^(\s+)defaults:\s*(#.*)?$/', $line)) {
                $defaultsIndex = $i;
                break;
            }
        }
        if (null === $defaultsIndex) {
            return null;
        }

        $parentIndent = \strlen($lines[$defaultsIndex]) - \strlen(ltrim($lines[$defaultsIndex]));
        $end = \count($lines);
        $childIndent = null;
        for ($i = $defaultsIndex + 1; $i < \count($lines); ++$i) {
            if ('' === trim($lines[$i]) || str_starts_with(ltrim($lines[$i]), '#')) {
                continue;
            }
            $indent = \strlen($lines[$i]) - \strlen(ltrim($lines[$i]));
            if ($indent <= $parentIndent) {
                $end = $i;
                break;
            }
            $childIndent ??= $indent;
        }
        $pad = str_repeat(' ', $childIndent ?? $parentIndent + 4);

        $insert = [];
        $lines = $this->ensureFlowListItem($lines, $defaultsIndex, $end, 'allow_headers', self::DEVICE_HEADER, $pad, $insert);
        if (null === $lines) {
            return null;
        }
        $lines = $this->ensureFlowListItem($lines, $defaultsIndex, $end, 'expose_headers', self::RETRY_AFTER_HEADER, $pad, $insert);
        if (null === $lines) {
            return null;
        }

        $credentialsFound = false;
        for ($i = $defaultsIndex + 1; $i < $end; ++$i) {
            if (1 === preg_match('/^(\s+)allow_credentials:\s*(\S+)/', $lines[$i], $m)) {
                $credentialsFound = true;
                if ('true' !== strtolower($m[2])) {
                    $lines[$i] = $m[1] . 'allow_credentials: true';
                }
            }
        }
        if (!$credentialsFound) {
            $insert[] = $pad . 'allow_credentials: true';
        }

        array_splice($lines, $defaultsIndex + 1, 0, $insert);

        return implode("\n", $lines);
    }

    /**
     * @param list<string> $lines
     * @param list<string> $insert lines to add right after `defaults:` (by reference)
     *
     * @return list<string>|null null = key present in a form we do not edit (block list…)
     */
    private function ensureFlowListItem(array $lines, int $from, int $to, string $key, string $item, string $pad, array &$insert): ?array
    {
        for ($i = $from + 1; $i < $to; ++$i) {
            if (1 !== preg_match('/^(\s+)' . $key . ':(.*)$/', $lines[$i], $m)) {
                continue;
            }
            $value = trim($m[2]);
            if (1 === preg_match('/^\[(.*)\]\s*(#.*)?$/', $value, $list)) {
                if (1 === preg_match('/[\'"]?' . preg_quote($item, '/') . '[\'"]?/i', $list[1]) || str_contains($list[1], '*')) {
                    return $lines;
                }
                $items = '' === trim($list[1]) ? "'" . $item . "'" : rtrim($list[1]) . ", '" . $item . "'";
                $lines[$i] = $m[1] . $key . ': [' . $items . ']' . (isset($list[2]) && '' !== $list[2] ? ' ' . $list[2] : '');

                return $lines;
            }

            return null;
        }

        $insert[] = $pad . $key . ": ['" . $item . "']";

        return $lines;
    }
}
