<?php

declare(strict_types=1);

namespace Musikhood\AuthClient\Install;

use Musikhood\AuthClient\Routing\PublicRoutes;
use Musikhood\AuthClient\Security\ApiTokenAuthenticator;
use Musikhood\AuthClient\Security\JwtCookieAuthenticator;
use Symfony\Component\Yaml\Exception\ParseException;
use Symfony\Component\Yaml\Yaml;

/**
 * Plans `config/packages/security.yaml`:
 *   - missing / stock Symfony file → the whole file is written (top-level
 *     `when@*` sections of the stock file are kept);
 *   - application's own firewalls → the coverage of the bundle routes is
 *     evaluated with Symfony's first-match semantics; already covered →
 *     no change, otherwise the exact fragment to paste is printed. A custom
 *     security.yaml is NEVER rewritten (comments, ordering and intent would
 *     be lost).
 */
final class SecurityConfigurator
{
    public const PATH = 'config/packages/security.yaml';

    private const PUBLIC_ACCESS = 'PUBLIC_ACCESS';

    public function plan(string $projectDir): PlannedChange
    {
        $file = $projectDir . '/' . self::PATH;
        if (!is_file($file)) {
            return PlannedChange::create(self::PATH, 'konfiguracja security dla bundla (firewall publiczny + API)', self::template());
        }

        $old = (string) file_get_contents($file);

        try {
            $parsed = Yaml::parse($old) ?? [];
        } catch (ParseException $e) {
            return PlannedChange::manual(self::PATH, sprintf('nie da się sparsować pliku (%s) — dopisz fragment ręcznie', $e->getMessage()), self::manualSnippet());
        }
        if (!\is_array($parsed)) {
            return PlannedChange::manual(self::PATH, 'nieoczekiwana struktura pliku — dopisz fragment ręcznie', self::manualSnippet());
        }

        $security = \is_array($parsed['security'] ?? null) ? $parsed['security'] : [];

        if ($this->isStock($parsed, $security)) {
            $preserved = array_filter($parsed, static fn (string|int $key): bool => \is_string($key) && str_starts_with($key, 'when@'), \ARRAY_FILTER_USE_KEY);
            $new = self::template() . ([] === $preserved ? '' : "\n" . Yaml::dump($preserved, 6, 4));

            return PlannedChange::modify(self::PATH, 'domyślny plik Symfony → konfiguracja bundla' . ([] === $preserved ? '' : ' (sekcje when@* zachowane)'), $old, $new);
        }

        $problems = $this->coverageProblems($security);
        if (null === $problems) {
            return PlannedChange::manual(self::PATH, 'firewalle z host/methods/request_matcher — nie oceniam automatycznie; porównaj z fragmentem i sprawdź auth-client:doctor', self::manualSnippet());
        }
        if ([] === $problems) {
            return PlannedChange::unchanged(self::PATH, 'trasy bundla już poprawnie skonfigurowane');
        }

        return PlannedChange::manual(self::PATH, 'własne firewalle — nie nadpisuję. Brakuje: ' . implode('; ', $problems), self::manualSnippet());
    }

    public static function template(): string
    {
        $pattern = PublicRoutes::pattern();
        $apiToken = ApiTokenAuthenticator::class;
        $jwtCookie = JwtCookieAuthenticator::class;

        return <<<YAML
            # Generated by `bin/console auth-client:install` (musikhood/auth-client-bundle).
            security:
                providers:
                    # The bundle's authenticators return the user directly — nothing to reload.
                    auth_client_users:
                        memory: ~

                firewalls:
                    dev:
                        pattern: ^/(_(profiler|wdt)|css|images|js)/
                        security: false

                    # Public routes of the bundle: login, 2FA steps, refresh, logout, webhook.
                    # They authorize themselves (password / mfa_token / refresh_token / signed JWT).
                    login:
                        pattern: '{$pattern}'
                        stateless: true
                        security: false

                    api:
                        pattern: ^/api
                        stateless: true
                        provider: auth_client_users
                        custom_authenticators:
                            # X-Api-Token (machine clients) or the BEARER cookie (browser).
                            - {$apiToken}
                            - {$jwtCookie}
                        entry_point: {$jwtCookie}

                access_control:
                    - { path: '{$pattern}', roles: PUBLIC_ACCESS }
                    - { path: ^/api, roles: IS_AUTHENTICATED_FULLY }

            YAML;
    }

    public static function manualSnippet(): string
    {
        $pattern = PublicRoutes::pattern();
        $apiToken = ApiTokenAuthenticator::class;
        $jwtCookie = JwtCookieAuthenticator::class;

        return <<<YAML
            security:
                firewalls:
                    # BEFORE any other firewall that matches ^/api:
                    login:
                        pattern: '{$pattern}'
                        stateless: true
                        security: false
                    api:
                        pattern: ^/api
                        stateless: true
                        custom_authenticators:
                            - {$apiToken}
                            - {$jwtCookie}
                        entry_point: {$jwtCookie}
                access_control:
                    # FIRST rule:
                    - { path: '{$pattern}', roles: PUBLIC_ACCESS }
                    # … your rules …
                    # LAST rule:
                    - { path: ^/api, roles: IS_AUTHENTICATED_FULLY }
            YAML;
    }

    /**
     * Stock = what `symfony/security-bundle`'s recipe ships (or less): only the
     * `dev` and a plain `main` firewall, in-memory providers, no access rules.
     *
     * @param array<mixed> $parsed
     * @param array<mixed> $security
     */
    private function isStock(array $parsed, array $security): bool
    {
        foreach (array_keys($parsed) as $key) {
            if ('security' !== $key && !(\is_string($key) && str_starts_with($key, 'when@'))) {
                return false;
            }
        }

        foreach (array_keys($security) as $key) {
            if (!\in_array($key, ['password_hashers', 'providers', 'firewalls', 'access_control'], true)) {
                return false;
            }
        }

        $firewalls = \is_array($security['firewalls'] ?? null) ? $security['firewalls'] : [];
        foreach ($firewalls as $name => $config) {
            if ('dev' === $name) {
                continue;
            }
            if ('main' !== $name || (\is_array($config) && [] !== array_diff(array_keys($config), ['lazy', 'provider']))) {
                return false;
            }
        }

        $providers = \is_array($security['providers'] ?? null) ? $security['providers'] : [];
        foreach ($providers as $provider) {
            if (!\is_array($provider) || [] !== array_diff(array_keys($provider), ['memory'])) {
                return false;
            }
        }

        return [] === ($security['access_control'] ?? []) || null === ($security['access_control'] ?? null);
    }

    /**
     * @param array<mixed> $security
     *
     * @return list<string>|null problems ([] = covered), null = cannot evaluate
     */
    private function coverageProblems(array $security): ?array
    {
        $firewalls = \is_array($security['firewalls'] ?? null) ? $security['firewalls'] : [];
        $rules = \is_array($security['access_control'] ?? null) ? array_values($security['access_control']) : [];
        $problems = [];

        $uncovered = [];
        foreach (PublicRoutes::PATHS as $path) {
            $firewall = $this->firstFirewall($firewalls, $path);
            if (false === $firewall) {
                return null;
            }
            $public = (null !== $firewall && false === ($firewall['security'] ?? true))
                || \in_array(self::PUBLIC_ACCESS, $this->firstRuleRoles($rules, $path, 'POST'), true);
            if (!$public) {
                $uncovered[] = $path;
            }
        }
        if ([] !== $uncovered) {
            $problems[] = 'publiczne trasy ' . implode(', ', $uncovered);
        }

        $firewall = $this->firstFirewall($firewalls, PublicRoutes::PROTECTED_PROBE_PATH);
        if (false === $firewall) {
            return null;
        }
        $authenticators = \is_array($firewall['custom_authenticators'] ?? null) ? $firewall['custom_authenticators'] : [];
        if (null === $firewall || false === ($firewall['security'] ?? true) || !\in_array(JwtCookieAuthenticator::class, $authenticators, true)) {
            $problems[] = 'firewall ^/api z ' . JwtCookieAuthenticator::class;
        }

        $roles = $this->firstRuleRoles($rules, PublicRoutes::PROTECTED_PROBE_PATH, 'GET');
        if ([] === $roles || \in_array(self::PUBLIC_ACCESS, $roles, true)) {
            $problems[] = 'reguła access_control { path: ^/api, roles: IS_AUTHENTICATED_FULLY }';
        }

        return $problems;
    }

    /**
     * @param array<mixed> $firewalls
     *
     * @return array<mixed>|null|false first matching firewall config, null = none, false = cannot evaluate
     */
    private function firstFirewall(array $firewalls, string $path): array|null|false
    {
        foreach ($firewalls as $config) {
            $config = \is_array($config) ? $config : [];
            if (isset($config['host']) || isset($config['methods']) || isset($config['request_matcher'])) {
                return false;
            }
            $pattern = $config['pattern'] ?? null;
            if (null === $pattern || (\is_string($pattern) && 1 === @preg_match('{' . $pattern . '}', $path))) {
                return $config;
            }
        }

        return null;
    }

    /**
     * @param list<mixed> $rules
     *
     * @return list<string>
     */
    private function firstRuleRoles(array $rules, string $path, string $method): array
    {
        foreach ($rules as $rule) {
            if (!\is_array($rule)) {
                continue;
            }
            $methods = $rule['methods'] ?? [];
            $methods = \is_string($methods) ? array_map('trim', explode(',', $methods)) : (\is_array($methods) ? $methods : []);
            if ([] !== $methods && !\in_array($method, array_map(static fn (mixed $m): string => strtoupper((string) $m), $methods), true)) {
                continue;
            }
            $pattern = $rule['path'] ?? null;
            if (null !== $pattern && !(\is_string($pattern) && 1 === @preg_match('{' . $pattern . '}', $path))) {
                continue;
            }
            $roles = $rule['roles'] ?? [];

            return array_values(array_map('strval', \is_array($roles) ? $roles : [$roles]));
        }

        return [];
    }
}
